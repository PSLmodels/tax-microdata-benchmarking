"""
Construct tmd_weights.csv.gz, a Tax-Calculator-style weights file for TAXYEAR+
consistent with the initial-year weights generated by the
create_taxcalc_input_variable.py script.
"""

import pandas as pd
from tmd.storage import STORAGE_FOLDER
from tmd.imputation_assumptions import TAXYEAR
from tmd.utils.weight_growth import cumulative_growth

FIRST_YEAR = TAXYEAR
LAST_YEAR = TAXYEAR + 53
VARFILE = STORAGE_FOLDER / "output" / "tmd.csv.gz"
WGTFILE = STORAGE_FOLDER / "output" / "tmd_weights.csv.gz"


def create_weights_file():
    """
    Create Tax-Calculator-style weights file for FIRST_YEAR through LAST_YEAR.
    """
    # get cumulative tax return growth relative to FIRST_YEAR
    growth = cumulative_growth(FIRST_YEAR, LAST_YEAR)

    # get FIRST_YEAR weights from VARFILE
    vdf = pd.read_csv(VARFILE)
    weights = vdf.s006

    # construct dictionary of weights by year
    wdict = {}
    for year in range(FIRST_YEAR, LAST_YEAR + 1):
        wdict[f"WT{year}"] = weights.copy() * growth[year]

    # write weights to CSV-formatted file
    wdf = pd.DataFrame.from_dict(wdict)
    wdf.to_csv(WGTFILE, index=False, float_format="%.5f", compression="gzip")


if __name__ == "__main__":
    create_weights_file()
